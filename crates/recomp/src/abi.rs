//! The guest ABI shared by the emitted C code and the Rust driver.
//!
//! `GuestState` is the twenty-slot machine state (sixteen registers
//! then N/Z/C/V) plus the bookkeeping fields the emitted code and the
//! host communicate through. `GuestOps` is the function-pointer table
//! the emitted code uses for memory: the host implements the
//! interpreter's exact load/store semantics (widths, sign extension,
//! misalignment quirks, waitstate charging) over the real bus, so the
//! translated code never touches memory directly.

/// Mirror of the C `struct oxy_state` (field order and widths must
/// stay in sync with [`header`]).
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GuestState {
    /// r0-r15; slot 15 is the PC the same way the IR's r15 slot is.
    pub r: [u32; 16],
    /// N flag, 0 or 1.
    pub n: u32,
    /// Z flag, 0 or 1.
    pub z: u32,
    /// C flag, 0 or 1.
    pub c: u32,
    /// V flag, 0 or 1.
    pub v: u32,
    /// The resume address when the code exits mid-function.
    pub pc: u32,
    /// Nonzero when the code exited before the function returned.
    pub exited: u32,
    /// The instruction state to resume in: 1 when THUMB, 0 when ARM.
    /// Exits that interwork overwrite it from the target's low bit.
    pub thumb: u32,
    /// Cycles charged since the host started this native call: one
    /// fetch per guest instruction through the host's cost model,
    /// real waitstate costs on the memory callbacks, and the lifted
    /// internal-cycle extras.
    pub cycles: u64,
    /// IR instructions executed, for the host's budget check.
    pub icount: u64,
}

/// `Size::Byte`.
pub const SIZE_BYTE: u32 = 0;
/// `Size::Half`.
pub const SIZE_HALF: u32 = 1;
/// `Size::Word`.
pub const SIZE_WORD: u32 = 2;

/// `LoadMode::Ldr`.
pub const MODE_LDR: u32 = 0;
/// `LoadMode::Swap`.
pub const MODE_SWAP: u32 = 1;
/// `LoadMode::Block`.
pub const MODE_BLOCK: u32 = 2;

/// Mirror of the C `struct oxy_ops`.
#[repr(C)]
pub struct GuestOps {
    /// Host context passed back to every callback (the driver's bus).
    pub ctx: *mut core::ffi::c_void,
    /// One load with the interpreter's semantics.
    pub load: unsafe extern "C" fn(
        ctx: *mut core::ffi::c_void,
        st: *mut GuestState,
        addr: u32,
        size: u32,
        signed_ext: u32,
        mode: u32,
    ) -> u32,
    /// One store. Returns nonzero when the store targets a page the
    /// host marks as translated code: the store is NOT performed, the
    /// host has set `st->exited` and `st->pc = pc`, and the emitted
    /// code must return immediately so the interpreter reruns the
    /// storing instruction (and the patched bytes after it). The `pc`
    /// argument is the storing instruction's guest address.
    pub store: unsafe extern "C" fn(
        ctx: *mut core::ffi::c_void,
        st: *mut GuestState,
        addr: u32,
        value: u32,
        size: u32,
        pc: u32,
    ) -> u32,
    /// One opcode fetch: charges `st->cycles` with the bus's fetch
    /// cost at `addr` (`width` in bytes, 4 or 2), keeping the
    /// sequential tracker and the Game Pak prefetch buffer exactly as
    /// the interpreter's per-instruction fetches do.
    pub fetch: unsafe extern "C" fn(
        ctx: *mut core::ffi::c_void,
        st: *mut GuestState,
        addr: u32,
        width: u32,
    ),
    /// Native execution stops (with `exited` set) once `icount`
    /// reaches this.
    pub budget: u64,
    /// Native execution also stops once charged `cycles` reach this,
    /// checked at the same backward edges and calls. The frame runner
    /// budgets units to the remaining cycles before the video frame
    /// boundary so a unit cannot overshoot it; unbounded callers set
    /// `u64::MAX` and rely on `budget` alone.
    pub cycle_budget: u64,
}

/// The C declarations every emitted module is compiled against: the
/// state and ops structs, the size/mode constants, and the arithmetic
/// helpers the emitter calls. Must stay in sync with [`GuestState`]
/// and [`GuestOps`].
pub fn header() -> &'static str {
    HEADER
}

const HEADER: &str = r#"/* Generated by oxyboy recomp; the ABI mirror lives in crates/recomp/src/abi.rs. */
#include <stdint.h>

struct oxy_state {
    uint32_t r[16];
    uint32_t n, z, c, v;
    uint32_t pc;
    uint32_t exited;
    uint32_t thumb;
    uint64_t cycles;
    uint64_t icount;
};

#define OXY_SIZE_BYTE 0u
#define OXY_SIZE_HALF 1u
#define OXY_SIZE_WORD 2u
#define OXY_MODE_LDR 0u
#define OXY_MODE_SWAP 1u
#define OXY_MODE_BLOCK 2u

struct oxy_ops {
    void* ctx;
    uint32_t (*load)(void* ctx, struct oxy_state* st, uint32_t addr, uint32_t size, uint32_t sext, uint32_t mode);
    /* Returns nonzero to abort the chunk: the store hit translated
     * code, the host set st->pc/st->exited, and the interpreter reruns
     * the storing instruction (pc argument). */
    uint32_t (*store)(void* ctx, struct oxy_state* st, uint32_t addr, uint32_t value, uint32_t size, uint32_t pc);
    /* One opcode fetch: charges the bus fetch cost into st->cycles
     * (width in bytes, 4 or 2). */
    void (*fetch)(void* ctx, struct oxy_state* st, uint32_t addr, uint32_t width);
    uint64_t budget;
    /* Backward edges and calls also exit once st->cycles reaches
     * this, so a unit cannot run past the scheduler's frame slice. */
    uint64_t cycle_budget;
};

/* a + b + cin with ARM carry/overflow (ARM ARM A2.3.1). */
static uint32_t oxy_add(uint32_t a, uint32_t b, uint32_t cin, uint32_t* co, uint32_t* vo) {
    uint64_t r = (uint64_t)a + (uint64_t)b + (uint64_t)cin;
    *co = (r >> 32) & 1u;
    *vo = ((~(a ^ b)) & (a ^ (uint32_t)r)) >> 31;
    return (uint32_t)r;
}

/* a - b - borrow with ARM carry (set when no borrow) and overflow. */
static uint32_t oxy_sub(uint32_t a, uint32_t b, uint32_t borrow, uint32_t* co, uint32_t* vo) {
    uint64_t r = (uint64_t)a - (uint64_t)b - (uint64_t)borrow;
    *co = ((r >> 63) & 1u) ^ 1u;
    *vo = ((a ^ b) & (a ^ (uint32_t)r)) >> 31;
    return (uint32_t)r;
}

static uint32_t oxy_shl(uint32_t v, uint32_t amt, uint32_t cin, uint32_t* co) {
    if (amt == 0u) { *co = cin; return v; }
    if (amt <= 31u) { *co = (v >> (32u - amt)) & 1u; return v << amt; }
    if (amt == 32u) { *co = v & 1u; return 0u; }
    *co = 0u; return 0u;
}

static uint32_t oxy_shr(uint32_t v, uint32_t amt, uint32_t cin, uint32_t* co) {
    if (amt == 0u) { *co = cin; return v; }
    if (amt <= 31u) { *co = (v >> (amt - 1u)) & 1u; return v >> amt; }
    if (amt == 32u) { *co = (v >> 31) & 1u; return 0u; }
    /* Beyond 32 no bit is shifted out: carry clear (A2.4). */
    *co = 0u; return 0u;
}

static uint32_t oxy_sar(uint32_t v, uint32_t amt, uint32_t cin, uint32_t* co) {
    uint32_t fill = (v >> 31) & 1u;
    if (amt == 0u) { *co = cin; return v; }
    if (amt >= 32u) { *co = fill; return 0u - fill; }
    *co = (v >> (amt - 1u)) & 1u;
    return (uint32_t)((int32_t)v >> amt);
}

static uint32_t oxy_ror(uint32_t v, uint32_t amt, uint32_t cin, uint32_t* co) {
    uint32_t n = amt & 31u;
    if (amt == 0u) { *co = cin; return v; }
    if (n == 0u) { *co = (v >> 31) & 1u; return v; }
    *co = (v >> (n - 1u)) & 1u;
    return (v >> n) | (v << (32u - n));
}
"#;
